/**
 * @file exporter.js - Report Generators (JSON, CSV, Markdown, TXT)
 */
import { promises as fs } from 'node:fs';
import { dirname } from 'node:path';

/**
 * Format results as JSON string
 * @param {string} username
 * @param {import('../core/types.js').ServiceResult[]} results
 * @param {number} durationMs
 * @returns {string}
 */
export function formatJson(username, results, durationMs) {
  const found = results.filter((r) => r.exists);
  return JSON.stringify(
    {
      target: username,
      timestamp: new Date().toISOString(),
      durationMs,
      totalChecked: results.length,
      totalFound: found.length,
      hits: found,
      allResults: results
    },
    null,
    2
  );
}

/**
 * Format results as CSV string
 * @param {string} username
 * @param {import('../core/types.js').ServiceResult[]} results
 * @returns {string}
 */
export function formatCsv(username, results) {
  const found = results.filter((r) => r.exists);
  const rows = [
    ['Username', 'Site', 'Category', 'Profile URL', 'Display Name', 'Avatar', 'Duration (ms)'].map((h) => `"${h}"`).join(',')
  ];

  for (const r of found) {
    const name = r.metadata?.name || '';
    const avatar = r.metadata?.avatarUrl || '';
    rows.push(
      [
        username,
        r.site,
        r.category,
        r.url,
        name.replace(/"/g, '""'),
        avatar.replace(/"/g, '""'),
        r.durationMs
      ]
        .map((val) => `"${val}"`)
        .join(',')
    );
  }

  return rows.join('\n');
}

/**
 * Format results as Markdown report
 * @param {string} username
 * @param {import('../core/types.js').ServiceResult[]} results
 * @param {number} durationMs
 * @returns {string}
 */
export function formatMarkdown(username, results, durationMs) {
  const found = results.filter((r) => r.exists);

  let md = `# 🔍 PatrickUser OSINT Investigation: @${username}\n\n`;
  md += `*The Mentalist Observational Digital Footprint Report*\n\n`;
  md += `- **Target Username:** \`${username}\`\n`;
  md += `- **Date:** ${new Date().toUTCString()}\n`;
  md += `- **Footprints Found:** ${found.length} / ${results.length}\n`;
  md += `- **Investigation Duration:** ${(durationMs / 1000).toFixed(2)}s\n\n`;

  md += `## 📋 Confirmed Digital Footprints\n\n`;
  md += `| Platform | Category | Profile URL | Detected Identity | Extra Clues |\n`;
  md += `| :--- | :--- | :--- | :--- | :--- |\n`;

  for (const r of found) {
    const meta = r.metadata || {};
    const name = meta.name ? `**${meta.name}**` : '—';
    const extraItems = [];
    if (meta.followers) extraItems.push(`${meta.followers} followers`);
    if (meta.extra?.streak) extraItems.push(`${meta.extra.streak}🔥 streak`);
    if (meta.extra?.totalKarma) extraItems.push(`${meta.extra.totalKarma} karma`);
    if (meta.extra?.publicRepos !== undefined) extraItems.push(`${meta.extra.publicRepos} repos`);
    if (meta.extra?.rapidRating) extraItems.push(`Rating: ${meta.extra.rapidRating}`);
    if (meta.extra?.tabcoins) extraItems.push(`TabCoins: ${meta.extra.tabcoins}`);
    const clues = extraItems.length > 0 ? extraItems.join(', ') : (meta.bio ? meta.bio.slice(0, 40) + '...' : '—');

    md += `| **${r.site}** | \`${r.category}\` | [${r.url}](${r.url}) | ${name} | ${clues} |\n`;
  }

  md += `\n---\n*Generated by [PatrickUser](https://github.com/patrickuser/patrickuser) — The Mentalist OSINT Hunter*\n`;
  return md;
}

/**
 * Export results to target file path
 * @param {string} filePath
 * @param {string} content
 */
export async function saveToFile(filePath, content) {
  await fs.mkdir(dirname(filePath), { recursive: true });
  await fs.writeFile(filePath, content, 'utf-8');
}

